export function resolveTerminalTheme(
  themeSetting: string | undefined,
  appAppearance: "light" | "dark",
): ITheme {
  const chosen = themeSetting || "auto";
  if (chosen === "auto") {
    return appAppearance === "light" ? DEFAULT_LIGHT_THEME : DEFAULT_DARK_THEME;
  }
  const found = TERMINAL_THEMES.find((t) => t.id === chosen);
  return found ? found.theme : appAppearance === "light" ? DEFAULT_LIGHT_THEME : DEFAULT_DARK_THEME;
}
